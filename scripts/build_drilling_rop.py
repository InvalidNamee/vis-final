"""Generate the built-in adapter and distributable zip from the uploadable case.

Run: python3 scripts/build_drilling_rop.py
The package folder remains the source of truth. No frontend build runtime required.
"""
import json
from pathlib import Path
from zipfile import ZipFile, ZIP_DEFLATED

ROOT = Path(__file__).resolve().parents[1]
PACKAGE = ROOT / 'drilling-rop-case'
manifest = json.loads((PACKAGE / 'case.json').read_text())
files = []
for path in sorted((PACKAGE / 'demo').rglob('*')):
    if path.is_file():
        files.append(dict(name=path.relative_to(PACKAGE).as_posix(), size=path.stat().st_size,
                          enc='text', data=path.read_text()))
payload = json.dumps(dict(manifest=manifest, files=files), ensure_ascii=False, separators=(',', ':'))
adapter = """// Generated by scripts/build_drilling_rop.py; edit drilling-rop-case/ instead.
(function (global) {
  'use strict';
  var pack = __PAYLOAD__;
  // Local uploads take precedence. Keep the original importer and its package contract.
  var sc = global.ATLAS.index.byScene[pack.manifest.sceneId];
  var existing = global.Cases.get(pack.manifest.id);
  if (existing) {
    if (sc && existing.tabs && existing.tabs.demo) sc.demo = true;
    return;
  }
  if (global.CaseImport.blockedList().indexOf(pack.manifest.id) >= 0) return;
  var c = pack.manifest;
  var cfg = c.tabs.demo;
  var handle = null;
  c.status = 'ready';
  c.tabs.demo = {
    label: cfg.label, intro: cfg.intro,
    mount: function (root, ctx) {
      handle = global.CaseDemoHost.create(root, { files: pack.files, demo: cfg, meta: c }, ctx);
    },
    unmount: function () { if (handle) { handle.destroy(); handle = null; } }
  };
  global.Cases.register(c);
  if (sc) sc.demo = true;
})(window);
""".replace('__PAYLOAD__', payload)
(ROOT / 'assets/cases/drilling-rop.case.js').write_text(adapter)
dist = ROOT / '.dist'
dist.mkdir(exist_ok=True)
with ZipFile(dist / 'drilling-rop-case.zip', 'w', ZIP_DEFLATED) as archive:
    for path in sorted(PACKAGE.rglob('*')):
        if path.is_file() and path.name != '.DS_Store':
            archive.write(path, path.relative_to(ROOT))
print('Generated assets/cases/drilling-rop.case.js and .dist/drilling-rop-case.zip')
