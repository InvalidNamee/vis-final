"""Shared adapter source and backward-compatible ROP build entry point."""
ADAPTER = """// Generated by scripts/build_drilling_cases.py; edit __PACKAGE__/ instead.
(function (global) {
  'use strict';
  var pack = __PAYLOAD__;
  // Local uploads take precedence. Keep the original importer and its package contract.
  var sc = global.ATLAS.index.byScene[pack.manifest.sceneId];
  var existing = global.Cases.get(pack.manifest.id);
  if (existing) {
    if (sc && existing.tabs && existing.tabs.demo) sc.demo = true;
    return;
  }
  if (global.CaseImport.blockedList().indexOf(pack.manifest.id) >= 0) return;
  var c = pack.manifest;
  var cfg = c.tabs.demo;
  var handle = null;
  c.status = 'ready';
  c.tabs.demo = {
    label: cfg.label, intro: cfg.intro,
    mount: function (root, ctx) {
      handle = global.CaseDemoHost.create(root, { files: pack.files, demo: cfg, meta: c }, ctx);
    },
    unmount: function () { if (handle) { handle.destroy(); handle = null; } }
  };
  global.Cases.register(c);
  if (sc) sc.demo = true;
})(window);
"""

